String? featureText(String key, String language) {
  final column = const {'en': 0, 'es': 1, 'de': 2, 'it': 3, 'ja': 4}[language];
  if (column == null) return null;
  final direct = featureStrings[key];
  if (direct != null) return direct[column];
  for (final template in _templates[column]!) {
    final match = template.pattern.firstMatch(key);
    if (match != null)
      return template.text.replaceAllMapped(
        _placeholders,
        (m) => match.group(template.names.indexOf(m.group(1)!) + 1)!,
      );
  }
  return null;
}

final _placeholders = RegExp(r'\{(\w+)\}');
final _templates = {
  for (var column = 0; column < 5; column++)
    column: [
      for (final entry in featureStrings.entries)
        if (entry.key.contains('{'))
          _FeatureTemplate(entry.key, entry.value[column]),
    ],
};

class _FeatureTemplate {
  final String text;
  final List<String> names = [];
  late final RegExp pattern;
  _FeatureTemplate(String key, this.text) {
    final pattern = StringBuffer('^');
    var offset = 0;
    for (final match in _placeholders.allMatches(key)) {
      pattern.write(RegExp.escape(key.substring(offset, match.start)));
      pattern.write('(.+?)');
      names.add(match.group(1)!);
      offset = match.end;
    }
    pattern.write(RegExp.escape(key.substring(offset)));
    pattern.write(r'$');
    this.pattern = RegExp(pattern.toString());
  }
}
